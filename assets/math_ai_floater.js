/* Auto-load REAL Live Viewers Widget */
(function(){
    if (window.__LIVE_VIEWERS_LOADED__) return;
    let prefix = 'assets/';
    const scripts = document.getElementsByTagName('script');
    for (let i = 0; i < scripts.length; i++) {
        const src = scripts[i].getAttribute('src') || '';
        if (src.includes('math_ai_floater.js')) {
            prefix = src.substring(0, src.indexOf('math_ai_floater.js'));
            break;
        }
    }
    const s = document.createElement('script');
    s.src = prefix + 'live_viewers.js';
    s.defer = true;
    document.head.appendChild(s);
})();

